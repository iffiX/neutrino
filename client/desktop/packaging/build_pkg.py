"""Build the client's Arch package.

    python3 client/desktop/packaging/build_pkg.py --output-dir dist/ --architecture x86_64

The same payload the .deb and the .rpm carry: the client compiled under
/opt/neutrino/client with the window's bindings inside it, the mount helper
compiled under its libexec at the path polkit pins, and the binaries the client
drives. It comes out of the same Debian 12 container as the other two, which
keeps the client's glibc floor, and is described as a PKGBUILD.

The same maintainer scripts too: every resident is asked to quit before its
files are taken, removing the package keeps each person's own configuration,
and the overlay daemons' units are registered on install and stopped on
removal.

Needs `makepkg`, which refuses to run as root, `bsdtar` and `zstd`, a C
compiler and patchelf for Nuitka, and `dpkg` for the viewer it unpacks out of
upstream's own .deb. This runs makepkg as the account --build-user names, and
as the invoking user or the container's build account without it.

Not pure: writes a package tree and runs makepkg.
"""

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import bundled  # noqa: E402
import payload  # noqa: E402
from gui_assets import ICONS_DIR  # noqa: E402
from shared import arch_build  # noqa: E402
from shared import edition_build  # noqa: E402

from neutrino_client.constants import (  # noqa: E402
    CLIENT_DESKTOP_NAME,
    CLIENT_MOUNT_HELPER_PATH,
    CLIENT_MOUNT_POLKIT_ACTION,
)

CLIENT_ROOT = payload.CLIENT_ROOT
PACKAGE_NAME = payload.PACKAGE_NAME

# The same C stack the .deb and the .rpm name, under the names the Arch family
# gives those libraries. Everything a feature of the client runs on is
# depended on, so a package that installed is a client whose every feature
# works.
RUNTIME_DEPENDS = (
    "webkit2gtk-4.1",
    "gobject-introspection-runtime",
    "gtk3",
    "polkit",
    "libayatana-appindicator",
    "cifs-utils",
    "libxcb",
    "xdotool",
    "libxfixes",
    "alsa-lib",
    "libpulse",
    "systemd-libs",
    "curl",
    "libva",
    "gst-plugins-base",
    "pam",
    "gst-plugin-pipewire",
)

PKGBUILD = """# Generated by neutrino's packaging build. Do not edit.
pkgname={name}
pkgver={version}
pkgrel=1
pkgdesc="Neutrino client"
arch=('{architecture}')
url="https://github.com/iffiX/neutrino"
license=('MIT')
depends=({depends})
conflicts=({conflicts})
options=({options})
install={name}.install

package() {{
    cp -a "{staged}/." "$pkgdir/"
}}
"""

INSTALL_SCRIPT = """@STOP@
register_desktop() {
    if [ -d /usr/share/icons/hicolor ]; then
        gtk-update-icon-cache -f /usr/share/icons/hicolor >/dev/null 2>&1 || true
    fi
    update-desktop-database /usr/share/applications >/dev/null 2>&1 || true
}

post_install() {
    register_desktop
@OVERLAY_START@
    echo ""
    echo "  Neutrino client installed. Open it and join a hub:"
    echo ""
    echo "      nclient gui"
    echo ""
}

pre_upgrade() {
    stop_residents
}

post_upgrade() {
    register_desktop
@OVERLAY_START@}

pre_remove() {
    stop_residents
@OVERLAY_STOP@}

post_remove() {
    rm -rf @PREFIX@
    rmdir /opt/neutrino 2>/dev/null || true
    if [ -d /run/systemd/system ]; then
        systemctl daemon-reload >/dev/null 2>&1 || true
    fi
}
"""


def main() -> int:
    """Build the package.

    Returns:
        The process exit status.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--output-dir", default="dist", help="where to write the package"
    )
    parser.add_argument(
        "--architecture",
        default=_host_architecture(),
        help="the architecture to build for",
    )
    parser.add_argument(
        "--build-user",
        default="",
        help="who runs makepkg, which refuses to run as root",
    )
    arguments = parser.parse_args()

    version = payload.version()
    architecture = _architecture(arguments.architecture)
    output_dir = Path(arguments.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as workdir:
        root = Path(workdir)
        staged = root / "staged"
        _lay_out(staged, version, architecture)
        payload.write(root / f"{PACKAGE_NAME}.install", install_script())
        payload.write(
            root / "PKGBUILD", pkgbuild(staged, version, architecture=architecture)
        )
        target = arch_build.build_package(
            root,
            output_dir,
            arch_build.builder_account(arguments.build_user),
            built=edition_build.built_name(
                "pkg", name=PACKAGE_NAME, version=version, architecture=architecture
            ),
            name=edition_build.asset_name(
                "pkg", name=PACKAGE_NAME, version=version, architecture=architecture
            ),
        )

    print(f"wrote {target} ({target.stat().st_size // 1024 // 1024} MiB)")
    return 0


def pkgbuild(staged: Path, version: str, *, architecture: str) -> str:
    """The PKGBUILD over a laid-out tree.

    Args:
        staged: The directory standing in for the filesystem root.
        version: The version being packaged.
        architecture: The Arch architecture name.

    Returns:
        The PKGBUILD's text.
    """
    return PKGBUILD.format(
        name=PACKAGE_NAME,
        version=version,
        architecture=architecture,
        depends=" ".join(f"'{name}'" for name in RUNTIME_DEPENDS),
        conflicts=" ".join(f"'{name}'" for name in payload.CONFLICTS),
        options=arch_build.ARCH_PACKAGE_OPTIONS,
        staged=staged,
    )


def install_script() -> str:
    """The pacman install script.

    Returns:
        The script's text.
    """
    return (
        INSTALL_SCRIPT.replace("@STOP@", payload.STOP_RESIDENTS)
        .replace("@OVERLAY_START@", _indented(payload.OVERLAY_UNITS_START))
        .replace("@OVERLAY_STOP@", _indented(payload.OVERLAY_UNITS_STOP))
        .replace("@PREFIX@", str(payload.INSTALL_PREFIX))
    )


def _lay_out(staged: Path, version: str, architecture: str) -> None:
    """Write everything the package installs.

    Args:
        staged: The directory standing in for the filesystem root.
        version: The version being packaged.
        architecture: The Arch architecture name.
    """
    compiled = payload.compile_linux(staged.parent / "build", architecture, version)
    payload.lay_out_compiled(staged, compiled, Path(CLIENT_MOUNT_HELPER_PATH))
    bundled.stage_linux_binaries(staged, architecture)
    payload.stage_linux_overlay(staged)
    payload.stage_licenses(staged)
    payload.require_glibc_floor(staged)
    _lay_out_desktop(staged)

    payload.write(
        staged / f"usr/share/polkit-1/actions/{CLIENT_MOUNT_POLKIT_ACTION}.policy",
        (
            CLIENT_ROOT
            / "neutrino_client/data/polkit"
            / f"{CLIENT_MOUNT_POLKIT_ACTION}.policy"
        ).read_text(encoding="utf-8"),
    )


def _lay_out_desktop(staged: Path) -> None:
    """Install the launcher and the icons.

    Args:
        staged: The directory standing in for the filesystem root.
    """
    desktop = CLIENT_ROOT / "neutrino_client/data/desktop"
    payload.write(
        staged / f"usr/share/applications/{CLIENT_DESKTOP_NAME}.desktop",
        (desktop / f"{CLIENT_DESKTOP_NAME}.desktop").read_text(encoding="utf-8"),
    )
    for source, edge in (("neutrino_256.png", 256), ("neutrino_48.png", 48)):
        destination = (
            staged
            / f"usr/share/icons/hicolor/{edge}x{edge}/apps/{CLIENT_DESKTOP_NAME}.png"
        )
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ICONS_DIR / source, destination)
        destination.chmod(0o644)


def _architecture(architecture: str) -> str:
    """The Arch name of a machine this package is published for.

    Args:
        architecture: The architecture, named however a packaging format
            names it.

    Returns:
        The Arch architecture name.

    Raises:
        SystemExit: When no Arch package is published for the machine.
    """
    name = payload.ARCH_ARCHITECTURES.get(payload.machine_name(architecture))
    if name is None:
        raise SystemExit(f"no Arch package is published for {architecture}")
    return name


def _indented(script: str) -> str:
    """A shell fragment indented one level, for the inside of a function."""
    return "".join(f"    {line}\n" if line else "\n" for line in script.splitlines())


def _host_architecture() -> str:
    """The Arch architecture name for the machine this runs on."""
    result = subprocess.run(["uname", "-m"], capture_output=True, text=True)
    return result.stdout.strip() or "x86_64"


if __name__ == "__main__":
    raise SystemExit(main())
