"""Fixed values of the file share module."""

# smb.conf stays the person's, a whole file an earlier version rendered
# included: the module's shares live in a file of its own, which smb.conf
# includes through one line the module adds after the [global] header. The
# marker is the first line of the module's file; the backup path is the
# copy an earlier version kept, left where it is.
SAMBA_CONF_PATH = "/etc/samba/smb.conf"
SAMBA_MODULE_CONF_PATH = "/etc/samba/neutrino.conf"
# Everything named with this prefix is the module's: at the first apply
# after an install or an adoption every such user is swept and the wanted
# ones made anew.
SAMBA_LINUX_USER_PREFIX = "neutrino-"
SAMBA_CONF_MARKER = (
    "# Generated by neutrino. Do not edit; change it on the hub instead."
)
SAMBA_CONF_BACKUP_PATH = "/etc/samba/smb.conf.before_neutrino"
SAMBA_GLOBAL_HEADER = "[global]"
SAMBA_STOCK_CONF_PATHS = (
    "/usr/share/samba/smb.conf",
    "/etc/samba/smb.conf.example",
    "/usr/share/doc/samba-common/examples/smb.conf.default",
)
SAMBA_MINIMAL_CONF = "[global]\n   server role = standalone server\n"
# What every share of the module's answers: the loopback, where the agent's
# relay delivers each client's connection.
SAMBA_SHARE_HOSTS_ALLOW = "127.0.0.1 ::1"
# The settings of the person's [global] that stop the module's shares from
# answering, each reported by its code and never changed.
SAMBA_DOMAIN_SECURITY_MODES = ("domain", "ads")
SAMBA_DOMAIN_SERVER_ROLES = (
    "member server",
    "active directory domain controller",
    "classic primary domain controller",
    "classic backup domain controller",
)
# What the module set on Linux: each SMB user's password as its SHA-256 and
# whether it turned the SELinux boolean on, root-only under the agent's work root.
SAMBA_RECORD_NAME = "samba.json"
# The SELinux boolean that lets smbd read and write the folder of any share,
# and the words of getenforce on a machine where SELinux is active.
SAMBA_SELINUX_BOOLEAN = "samba_export_all_rw"
SAMBA_SELINUX_ACTIVE_MODES = ("Enforcing", "Permissive")

# Linux: the SMB user of an enabled account is a system account the module
# makes, with no home, no login shell and this comment, by which the module
# tells its own accounts from the machine's when one is dropped.
SAMBA_LINUX_USER_COMMENT = "neutrino file share"
SAMBA_LINUX_NOLOGIN_SHELLS = (
    "/usr/sbin/nologin",
    "/sbin/nologin",
    "/usr/bin/nologin",
    "/bin/false",
)

# Linux: the directory beside smb.conf holding one file per SMB user, named
# after the user, which a share the file names itself includes by the
# connected user's name, so the share writes files as that user's account.
SAMBA_USERS_DIR = "/etc/samba/neutrino_users"
SAMBA_USERS_FILE_SUFFIX = ".conf"
SAMBA_USERS_INCLUDE = f"{SAMBA_USERS_DIR}/%U{SAMBA_USERS_FILE_SUFFIX}"

# Debian names the unit after the binary; the RHEL family ships one
# smb.service.
SAMBA_SERVICES = {"debian": "smbd", "rhel": "smb", "arch": "smb"}
SAMBA_DEFAULT_SERVICE = "smbd"
# The server binary, which says Samba is on the machine when no package is named.
SAMBA_BINARY_NAME = "smbd"

# On Windows and macOS the module drives the system's own SMB server. What
# it made there is listed in this file under the agent's work root, and
# only what is both listed and marked is ever changed or removed.
SAMBA_NATIVE_RECORD_NAME = "samba_native.json"
# How long one reading of the server's state is believed.
SAMBA_NATIVE_STATUS_TTL_S = 30.0

# Windows: the start of the description of every share the module made,
# which is also the description of every account it made.
SAMBA_WINDOWS_MARKER = "neutrino:"
# The firewall rule an earlier version blocked SMB with; the module makes
# no rule now, and deletes this one at the first apply that finds it.
SAMBA_WINDOWS_FENCE_RULE = "neutrino_smb_fence"
# The folder under an account's share path that OpenSSH reads the account's
# own files from; the module's SMB user is granted nothing in it.
SAMBA_WINDOWS_SSH_DIR_NAME = ".ssh"
# The event log the SMB server writes its own events to.
SAMBA_WINDOWS_SERVER_LOG = "Microsoft-Windows-SMBServer/Operational"
# The rights that keep a share account off the console and off RDP.
SAMBA_WINDOWS_DENIED_RIGHTS = (
    "SeDenyInteractiveLogonRight",
    "SeDenyRemoteInteractiveLogonRight",
)
# A share's rights as the SMB server and as the folder's ACL name them.
SAMBA_WINDOWS_SHARE_CHANGE = "Change"
SAMBA_WINDOWS_SHARE_READ = "Read"
SAMBA_WINDOWS_FOLDER_CHANGE = "(OI)(CI)M"
SAMBA_WINDOWS_FOLDER_READ = "(OI)(CI)RX"
# The access rule each folder right leaves, as the PowerShell host reads it:
# the FileSystemRights, the InheritanceFlags (ContainerInherit and
# ObjectInherit) and the PropagationFlags.
SAMBA_WINDOWS_FOLDER_RULES = {
    SAMBA_WINDOWS_FOLDER_CHANGE: (0x1301BF, 3, 0),
    SAMBA_WINDOWS_FOLDER_READ: (0x1200A9, 3, 0),
}
# The account a share with no users is granted to, so the server never
# falls back to granting Everyone.
SAMBA_WINDOWS_SHARE_OWNER = "BUILTIN\\Administrators"

# macOS: smbd's launchd job and the plist it loads from.
SAMBA_DARWIN_SMBD_TARGET = "system/com.apple.smbd"
SAMBA_DARWIN_SMBD_PLIST = "/System/Library/LaunchDaemons/com.apple.smbd.plist"
# The start of the record name of every share point the module made.
SAMBA_DARWIN_SHARE_PREFIX = "neutrino_"
# The refusals of one account an apply on Windows or macOS makes once every
# other account and every share is applied.
SAMBA_ACCOUNT_REFUSALS = ("user_create_failed", "user_record_unusable")
# The words every full name of an account the module made starts with;
# the account's own name follows them, since sysadminctl refuses a second
# account with a full name that exists. Accounts made before carry the
# words alone.
SAMBA_DARWIN_ACCOUNT_NAME = "neutrino file share"
# What an account's record holds once it can sign in.
SAMBA_DARWIN_ACCOUNT_KEYS = (
    "UniqueID",
    "PrimaryGroupID",
    "UserShell",
    "NFSHomeDirectory",
)
# The prefix NSLog writes before a tool's line: date, time, tool[pid:tid].
SAMBA_DARWIN_LOG_PREFIX = r"^\S+ \S+ \S+\[\d+:\d+\] "
# The group macOS limits SMB to, where the system has one.
SAMBA_DARWIN_ACCESS_GROUP = "com.apple.access_smb"
# What the unified log holds of smbd over the last quarter hour.
SAMBA_DARWIN_SERVER_LOG_COMMAND = (
    "log",
    "show",
    "--predicate",
    'process == "smbd"',
    "--last",
    "15m",
    "--style",
    "compact",
)
# The pf anchor an earlier version fenced SMB in, and the rules file it
# kept under the work root; the module fences nothing now, and the first
# apply that finds the file empties the anchor and deletes the file.
SAMBA_DARWIN_PF_ANCHOR = "com.apple/neutrino_smb"
SAMBA_DARWIN_PF_RULES_NAME = "samba_pf.conf"
# The access-control entries a share grants an account.
SAMBA_DARWIN_ACL_CHANGE = (
    "list,add_file,search,delete,add_subdirectory,delete_child,readattr,"
    "writeattr,readextattr,writeextattr,readsecurity,read,write,append,execute,"
    "file_inherit,directory_inherit"
)
SAMBA_DARWIN_ACL_READ = (
    "list,search,readattr,readextattr,readsecurity,read,execute,"
    "file_inherit,directory_inherit"
)
# An account's login shell: none.
SAMBA_DARWIN_SHELL = "/usr/bin/false"
SAMBA_DARWIN_HOME = "/var/empty"


def samba_unit(family: str) -> str:
    """The unit this family's Samba runs as.

    Args:
        family: The distribution family.

    Returns:
        The unit name, with its suffix.
    """
    return f"{SAMBA_SERVICES.get(family, SAMBA_DEFAULT_SERVICE)}.service"
