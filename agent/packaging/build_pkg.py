"""Build the agent's Arch package.

    python3 agent/packaging/build_pkg.py --output-dir dist/ --architecture x86_64

The same payload the .deb and the .rpm carry, under /opt/neutrino/agent: its
own interpreter. It is described as a PKGBUILD and built in a container of
its family, with RustDesk's host taken out of upstream's Arch package.

Needs `makepkg`, which refuses to run as root, and `bsdtar`. This runs makepkg
as the account --build-user names, and as the invoking user or the container's
build account without it.

Not pure: writes a package tree and runs makepkg.
"""

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import payload  # noqa: E402
from shared import arch_build  # noqa: E402
from shared import edition_build  # noqa: E402

AGENT_ROOT = payload.AGENT_ROOT
PACKAGE_NAME = payload.PACKAGE_NAME

UNIT_DIR = "usr/lib/systemd/system"

# The agent is a headless service; the interpreter it runs from is its own.
# The rest is what the RustDesk host the package carries loads, under the
# names upstream's Arch package gives those libraries.
RUNTIME_DEPENDS = (
    "systemd",
    "gtk3",
    "libxcb",
    "xdotool",
    "libxfixes",
    "alsa-lib",
    "libpulse",
    "systemd-libs",
    "curl",
    "libva",
    "gst-plugins-base",
    "pam",
    "gst-plugin-pipewire",
)

PKGBUILD = """# Generated by neutrino's packaging build. Do not edit.
pkgname={name}
pkgver={version}
pkgrel=1
pkgdesc="Neutrino device agent"
arch=('{architecture}')
url="https://github.com/iffiX/neutrino"
license=('MIT')
depends=({depends})
options=({options})
install={name}.install

package() {{
    cp -a "{staged}/." "$pkgdir/"
}}
"""

INSTALL_SCRIPT = """@PRUNE@
post_install() {
    systemctl daemon-reload >/dev/null 2>&1 || true
    # The agent runs from install: unbound it waits for a link, and its control
    # socket serves nagent.
    systemctl enable --now neutrino_agent.service >/dev/null 2>&1 || true
    if ! @BOUND_TEST@; then
        echo ""
        echo "  Neutrino agent installed. Join a hub with:"
        echo ""
        echo "      sudo nagent join <enrollment link>"
        echo ""
    fi
}

post_upgrade() {
    pacman -Qlq @NAME@ | sed 's:/*$::' | prune_untracked @PREFIX@
    systemctl daemon-reload >/dev/null 2>&1 || true
    # An upgrade restarts the running agent: the self-update ends here, and
    # without the restart the old process keeps running.
    systemctl try-restart neutrino_agent.service >/dev/null 2>&1 || true
    systemctl enable --now neutrino_agent.service >/dev/null 2>&1 || true
}

pre_remove() {
    # Removal is this machine leaving: the hub is told, and an unreachable
    # hub does not block the removal.
    nagent leave --yes 2>&1 || true
    systemctl stop neutrino_agent.service >/dev/null 2>&1 || true
    systemctl disable neutrino_agent.service >/dev/null 2>&1 || true
    # What the modules added in order to run goes with the agent: their
    # units. Shares, accounts and the modules' data stay.
    nagent service uninstall --yes 2>&1 || true
}

post_remove() {
    systemctl daemon-reload >/dev/null 2>&1 || true
    # What pacman leaves once its own files are gone: the bytecode the
    # interpreter wrote beside them, and the vendored tree's own directories.
    rm -rf @PREFIX@
    rm -rf @VENDOR@
    rmdir /opt/neutrino /usr/lib/neutrino 2>/dev/null || true
    echo "  Leaving /etc/neutrino/agent in place; remove it by hand if this"
    echo "  machine is not going to rejoin a hub."
}
"""

WRAPPER = """#!/bin/sh
# The agent runs from the interpreter the package carries, never the system
# one.
exec {python}/bin/python3 -m neutrino_agent.cli.entry "$@"
"""


def main() -> int:
    """Build the package.

    Returns:
        The process exit status.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--output-dir", default="dist", help="where to write the package"
    )
    parser.add_argument(
        "--architecture",
        default=_host_architecture(),
        help="the architecture to build for",
    )
    parser.add_argument(
        "--build-user",
        default="",
        help="who runs makepkg, which refuses to run as root",
    )
    arguments = parser.parse_args()

    version = payload.version()
    architecture = _architecture(arguments.architecture)
    output_dir = Path(arguments.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory() as workdir:
        root = Path(workdir)
        staged = root / "staged"
        _lay_out(staged, version, architecture)
        payload.write(root / f"{PACKAGE_NAME}.install", install_script())
        payload.write(
            root / "PKGBUILD", pkgbuild(staged, version, architecture=architecture)
        )
        target = arch_build.build_package(
            root,
            output_dir,
            arch_build.builder_account(arguments.build_user),
            built=edition_build.built_name(
                "pkg", name=PACKAGE_NAME, version=version, architecture=architecture
            ),
            name=edition_build.asset_name(
                "pkg", name=PACKAGE_NAME, version=version, architecture=architecture
            ),
        )

    print(f"wrote {target} ({target.stat().st_size // 1024 // 1024} MiB)")
    return 0


def pkgbuild(staged: Path, version: str, *, architecture: str) -> str:
    """The PKGBUILD over a laid-out tree.

    Args:
        staged: The directory standing in for the filesystem root.
        version: The version being packaged.
        architecture: The Arch architecture name.

    Returns:
        The PKGBUILD's text.
    """
    return PKGBUILD.format(
        name=PACKAGE_NAME,
        version=version,
        architecture=architecture,
        depends=" ".join(f"'{name}'" for name in RUNTIME_DEPENDS),
        options=arch_build.ARCH_PACKAGE_OPTIONS,
        staged=staged,
    )


def install_script() -> str:
    """The pacman install script.

    Returns:
        The script's text.
    """
    return (
        INSTALL_SCRIPT.replace("@PRUNE@", payload.PRUNE_UNTRACKED)
        .replace("@NAME@", PACKAGE_NAME)
        .replace("@PREFIX@", str(payload.INSTALL_PREFIX))
        .replace("@VENDOR@", str(payload.VENDOR_PREFIX))
        .replace(
            "@BOUND_TEST@",
            payload.AGENT_BOUND_TEST.format(path=payload.AGENT_BINDING_PATH),
        )
    )


def _lay_out(staged: Path, version: str, architecture: str) -> None:
    """Write everything the package installs.

    Args:
        staged: The directory standing in for the filesystem root.
        version: The version being packaged.
        architecture: The Arch architecture name.
    """
    programs = payload.go_programs(payload.go_target("linux", architecture))
    staged_python = staged / str(payload.PYTHON_DIR).lstrip("/")
    payload.stage_linux_interpreter(staged_python, architecture)
    payload.stage_agent_tree(payload.site_packages_of(staged_python), version)
    payload.compile_bytecode(staged_python, payload.PYTHON_DIR)
    payload.strip_build_paths(staged_python, staged)
    payload.stage_rustdesk(staged, architecture, "pkg")
    payload.stage_go_programs(
        staged / str(payload.INSTALL_PREFIX / payload.GO_BIN_DIR_NAME).lstrip("/"),
        programs,
    )
    payload.stage_licenses(staged)
    payload.require_glibc_floor(staged)

    payload.write(
        staged / "usr/bin/nagent",
        WRAPPER.format(python=payload.PYTHON_DIR),
        is_executable=True,
    )
    payload.write(
        staged / UNIT_DIR / "neutrino_agent.service",
        (AGENT_ROOT / "neutrino_agent/data/systemd/neutrino_agent.service").read_text(
            encoding="utf-8"
        ),
    )


def _architecture(architecture: str) -> str:
    """The Arch name of a machine this package is published for.

    Args:
        architecture: The architecture, named however a packaging format
            names it.

    Returns:
        The Arch architecture name.

    Raises:
        SystemExit: When no Arch package is published for the machine.
    """
    name = payload.ARCH_ARCHITECTURES.get(payload.machine_name(architecture))
    if name is None:
        raise SystemExit(f"no Arch package is published for {architecture}")
    return name


def _host_architecture() -> str:
    """The Arch architecture name for the machine this runs on."""
    result = subprocess.run(["uname", "-m"], capture_output=True, text=True)
    return result.stdout.strip() or "x86_64"


if __name__ == "__main__":
    raise SystemExit(main())
