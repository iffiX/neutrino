"""The module's own file, checked line by line and by Samba itself."""

import shutil
import subprocess

import pytest

from neutrino_agent.modules.samba.config import SambaConfig
from neutrino_agent.modules.samba.renderer import SambaConfigRenderer


def render(config_data: dict) -> str:
    config = SambaConfig.from_dict(config_data)
    config.validate()
    return SambaConfigRenderer(config=config).render()


def without_comments(rendered: str) -> str:
    return "\n".join(
        line for line in rendered.splitlines() if not line.strip().startswith("#")
    )


def validate_smb_conf(rendered: str, tmp_path) -> None:
    if shutil.which("testparm") is None:
        pytest.skip("samba is not installed here")
    path = tmp_path / "smb.conf"
    path.write_text(rendered, encoding="utf-8")
    result = subprocess.run(
        ["testparm", "-s", str(path)], capture_output=True, text=True
    )
    assert result.returncode == 0, result.stderr


BASIC = {
    "shares": [{"name": "share", "path": "/srv/share", "comment": "Shared space"}],
    "users": ["ann", "bob"],
}


def test_samba_itself_accepts_the_render(tmp_path):
    validate_smb_conf(render(BASIC), tmp_path)


def test_the_file_has_no_global_section_and_each_share_answers_the_loopback():
    rendered = without_comments(render(BASIC))

    assert "[global]" not in rendered
    assert "hosts deny" not in rendered
    assert "load printers" not in rendered
    assert "map to guest" not in rendered
    assert "unix password sync" not in rendered
    assert rendered.count("hosts allow = 127.0.0.1 ::1") == 1


def test_each_share_admits_its_own_smb_user_and_writes_as_the_account():
    data = {
        "shares": [
            {
                "name": "ann",
                "path": "/home/ann",
                "valid_users": ["neutrino-ann"],
                "force_user": "ann",
            },
            {
                "name": "bob",
                "path": "/home/bob",
                "valid_users": ["neutrino-bob"],
                "force_user": "bob",
            },
            {"name": "pool", "path": "/pool", "valid_users": ["neutrino-ann"]},
        ],
        "users": ["neutrino-ann", "neutrino-bob"],
    }

    rendered = without_comments(render(data))

    ann_block = rendered.split("[ann]")[1].split("[bob]")[0]
    bob_block = rendered.split("[bob]")[1].split("[pool]")[0]
    pool_block = rendered.split("[pool]")[1]
    assert "valid users = neutrino-ann" in ann_block
    assert "force user = ann" in ann_block
    assert "include" not in ann_block
    assert "valid users = neutrino-bob" in bob_block
    assert "force user = bob" in bob_block
    assert "force user" not in pool_block
    assert "include = /etc/samba/neutrino_users/%U.conf" in pool_block
    assert "force group" not in rendered
    assert "create mask" not in rendered
    assert "directory mask" not in rendered


def test_each_smb_user_has_a_file_forcing_its_account_for_the_named_shares():
    config = SambaConfig.from_dict(
        {
            "shares": [
                {
                    "name": "ann",
                    "path": "/home/ann",
                    "valid_users": ["neutrino-ann"],
                    "force_user": "ann",
                },
                {"name": "pool", "path": "/pool", "valid_users": ["neutrino-ann"]},
            ],
            "users": ["neutrino-ann"],
        }
    )

    files = SambaConfigRenderer(config=config).render_user_files()

    assert files == {
        "neutrino-ann.conf": (
            "# Generated by neutrino. Do not edit; change it on the hub instead.\n"
            "   force user = ann\n"
        )
    }


def test_a_share_naming_no_user_admits_every_configured_user():
    rendered = without_comments(
        render(
            {"shares": [{"name": "open", "path": "/srv/open"}], "users": ["ann", "bob"]}
        )
    )

    assert "valid users = ann bob" in rendered


def test_the_first_line_is_the_modules_marker():
    assert render(BASIC).splitlines()[0] == (
        "# Generated by neutrino. Do not edit; change it on the hub instead."
    )


def test_a_read_only_share_says_so():
    data = {
        "shares": [{"name": "archive", "path": "/srv/a", "is_read_only": True}],
        "users": [],
    }

    rendered = without_comments(render(data))

    assert "read only = yes" in rendered


def test_no_shares_renders_the_marker_alone(tmp_path):
    rendered = render({"shares": [], "users": ["ann"]})

    validate_smb_conf(rendered, tmp_path)
    assert rendered.strip() == (
        "# Generated by neutrino. Do not edit; change it on the hub instead."
    )
