import { useEffect, useState } from "react";

import { ErrorPanel } from "./error_panel";
import { Icon } from "./icon";
import { apiPost, describeError } from "../api_client";
import { copyText } from "../copy_text";
import { t, useLanguage } from "../i18n";
import { useApiResource } from "../use_api_resource";
import { useConfirm } from "../use_confirm";
import type {
  GeneratedCredentialItemView,
  GeneratedCredentialListView,
  GeneratedCredentialRequest,
  GeneratedCredentialRevealView,
} from "../api_types";

import "./generated_credentials_section.css";

/**
 * The Credentials page's **Generated by the hub**: one block per machine and
 * a row per secret the hub made for it. A password is masked until
 * **Reveal**; **Reveal** and **Copy** each ask the hub, which logs the read.
 * An SSH key shows its fingerprint in the clear. **Rotate** asks once and
 * acts at once.
 */

const GENERATED_PATH = "/hub/credential/generated";

const KIND_SSH_KEY = "ssh_key";
const KIND_SEAT_PASSWORD = "seat_password";

/** What a masked password shows in place of its value. */
const MASK = "••••••••••••";

/** How long a copy's confirmation stays. */
const COPIED_CLEAR_MS = 1600;

/** The body of the Rotate dialog, by kind. */
const ROTATE_BODY_KEYS: Record<string, string> = {
  smb_password: "ui.credentials.rotate_smb_body", // scan: allow
  seat_password: "ui.credentials.rotate_seat_body", // scan: allow
  ssh_key: "ui.credentials.rotate_ssh_body",
};

export function GeneratedCredentialsSection() {
  // Redrawn when the panel's language changes.
  useLanguage();
  const resource = useApiResource<GeneratedCredentialListView>(GENERATED_PATH);
  const confirm = useConfirm();
  const [error, setError] = useState<string | null>(null);
  const machines = resource.data?.machines ?? [];

  const rotateNow = async (
    deviceId: string,
    item: GeneratedCredentialItemView,
  ) => {
    setError(null);
    try {
      resource.setData(
        await apiPost<GeneratedCredentialListView>(
          `${GENERATED_PATH}/rotate`,
          requestOf(deviceId, item),
        ),
      );
    } catch (cause: unknown) {
      setError(describeError(cause));
    }
  };

  const rotate = (deviceId: string, item: GeneratedCredentialItemView) =>
    confirm.ask({
      title: t("ui.credentials.rotate_title", { name: itemLabel(item) }),
      body: t(ROTATE_BODY_KEYS[item.kind] ?? "ui.credentials.rotate_smb_body"),
      confirmLabel: t("ui.credentials.rotate"),
      onConfirm: () => void rotateNow(deviceId, item),
    });

  return (
    <section className="settings_group">
      <div className="settings_group_title">
        <h2>{t("ui.credentials.generated_title")}</h2>
      </div>
      <p className="field_hint">{t("ui.credentials.generated_hint")}</p>

      {resource.error !== null && (
        <ErrorPanel message={resource.error} onRetry={resource.reload} />
      )}
      {error !== null && (
        <div className="notice notice--error">
          <Icon name="alert" size={15} />
          <div className="notice_body">{error}</div>
        </div>
      )}

      {machines.length === 0 ? (
        resource.data !== null && (
          <div className="keys_empty">
            <Icon name="key" size={22} />
            <span className="keys_empty_title">
              {t("ui.credentials.generated_empty")}
            </span>
          </div>
        )
      ) : (
        <div className="generated_machines">
          {machines.map((machine) => (
            <div key={machine.device_id} className="generated_machine">
              <h3 className="generated_machine_name">{machine.name}</h3>
              {machine.items.map((item) => (
                <GeneratedRow
                  key={`${item.kind}:${item.account}`}
                  deviceId={machine.device_id}
                  item={item}
                  onRotate={() => rotate(machine.device_id, item)}
                />
              ))}
            </div>
          ))}
        </div>
      )}
      {confirm.modal}
    </section>
  );
}

interface GeneratedRowProps {
  deviceId: string;
  item: GeneratedCredentialItemView;
  onRotate: () => void;
}

function GeneratedRow({ deviceId, item, onRotate }: GeneratedRowProps) {
  // Redrawn when the panel's language changes.
  useLanguage();
  // The opened password while Reveal shows it; dropped by Hide and on leaving.
  const [value, setValue] = useState<string | null>(null);
  const [isCopied, setIsCopied] = useState(false);
  const [isBusy, setIsBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const isKey = item.kind === KIND_SSH_KEY;

  useEffect(() => {
    if (!isCopied) {
      return;
    }
    const timer = window.setTimeout(() => setIsCopied(false), COPIED_CLEAR_MS);
    return () => window.clearTimeout(timer);
  }, [isCopied]);

  const reveal = async (): Promise<string | null> => {
    setIsBusy(true);
    setError(null);
    try {
      const opened = await apiPost<GeneratedCredentialRevealView>(
        `${GENERATED_PATH}/reveal`,
        requestOf(deviceId, item),
      );
      return opened.value;
    } catch (cause: unknown) {
      setError(describeError(cause));
      return null;
    } finally {
      setIsBusy(false);
    }
  };

  const toggleReveal = async () => {
    if (value !== null) {
      setValue(null);
      return;
    }
    setValue(await reveal());
  };

  const copy = async () => {
    const text = isKey ? item.fingerprint : await reveal();
    if (text === null) {
      return;
    }
    try {
      await copyText(text);
      setIsCopied(true);
    } catch {
      // The value stays on screen to be selected by hand.
    }
  };

  return (
    <div className="generated_row">
      <span className="generated_row_label">{itemLabel(item)}</span>
      <span className="generated_row_value mono">
        {isKey ? item.fingerprint : (value ?? MASK)}
      </span>
      <div className="generated_row_actions">
        {!isKey && (
          <button
            type="button"
            className="button button--small button--ghost"
            disabled={isBusy}
            onClick={() => void toggleReveal()}
          >
            <Icon name={value === null ? "eye" : "eye_off"} size={13} />
            {value === null
              ? t("ui.credentials.reveal")
              : t("ui.credentials.hide")}
          </button>
        )}
        <button
          type="button"
          className="button button--small button--ghost"
          disabled={isBusy || (isKey && item.fingerprint === "")}
          onClick={() => void copy()}
        >
          <Icon name={isCopied ? "check" : "file"} size={13} />
          {isCopied ? t("ui.copy_button.copied") : t("ui.credentials.copy")}
        </button>
        <button
          type="button"
          className="button button--small button--ghost"
          disabled={isBusy}
          onClick={onRotate}
        >
          <Icon name="refresh" size={13} />
          {t("ui.credentials.rotate")}
        </button>
      </div>
      {error !== null && <span className="field_error">{error}</span>}
    </div>
  );
}

/** The row's name: its kind and its account. */
function itemLabel(item: GeneratedCredentialItemView): string {
  if (item.kind === KIND_SEAT_PASSWORD) {
    return t("ui.credentials.seat_password");
  }
  if (item.kind === KIND_SSH_KEY) {
    return t("ui.credentials.ssh_key", { account: item.account });
  }
  return t("ui.credentials.smb_password", { account: item.account });
}

function requestOf(
  deviceId: string,
  item: GeneratedCredentialItemView,
): GeneratedCredentialRequest {
  return { device_id: deviceId, kind: item.kind, account: item.account };
}
